"""Generate docs/reference/commands.md from the Typer app.

The command reference is generated, not hand-written: every command's
help text, usage line, and options come straight from the app
definition, so CLI help and docs cannot drift. Run after changing any
command surface and commit the result; CI regenerates and fails on
git diff (the committed-openapi + drift-test pattern).

Introspection goes through click (Typer builds on it): typer.main
.get_group(app) yields the full command tree, and each command's
params carry name/type/required/help. No rich rendering involved, so
the output is deterministic — no ANSI, no terminal width coupling.
"""

import re
from pathlib import Path

import click
import typer

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "docs" / "reference" / "commands.md"
HEADER = """\
# Command reference

<!-- AUTO-GENERATED by scripts/generate_cli_reference.py — do not edit.
     Run `python scripts/generate_cli_reference.py` after changing any
     command surface; CI regenerates this file and fails on drift. -->

Every command ships the same information on your terminal via
`campus <command> --help`.
"""


def _clean(text: str | None) -> str:
    """Normalize a help string to single-line markdown-safe text."""
    if not text:
        return ""
    return re.sub(r"\s+", " ", text).strip()


def _slug(text: str) -> str:
    """Anchor for a heading, matching Material's slugging (the heading
    is the command path in backticks; underscores survive slugifying).
    """
    return text.lower().replace(" ", "-")


def _usage_line(group_path: list[str], cmd: click.Command) -> str:
    """Build the usage line from the command's own params."""
    parts = ["campus", *group_path, cmd.name]
    args = []
    options = False
    for param in cmd.params:
        if isinstance(param, click.Argument):
            metavar = getattr(param, "metavar", None) or param.name.upper()
            if param.required:
                args.append(metavar)
            else:
                args.append(f"[{metavar}]")
        elif isinstance(param, click.Option):
            options = True
    if options:
        parts.append("[OPTIONS]")
    return " ".join(parts + args)


def _render_params(cmd: click.Command) -> list[str]:
    """Render options and arguments as markdown definition lines."""
    lines: list[str] = []
    for param in cmd.params:
        if isinstance(param, click.Argument):
            metavar = getattr(param, "metavar", None) or param.name.upper()
            req = " (required)" if param.required else ""
            help_ = _clean(param.help) or _clean(param.name)
            lines.append(f"- `{metavar}`{req} — {help_}.")
        elif isinstance(param, click.Option):
            flags = "/".join([*param.opts, *param.secondary_opts])
            bits = [f"`{flags}`"]
            type_name = getattr(param.type, "name", None)
            if type_name and type_name != "boolean":
                bits.append(type_name)
            if param.required:
                bits.append("required")
            elif param.default not in (None, (), False, ""):
                bits.append(f"default: `{param.default}`")
            entry = ", ".join(bits)
            help_ = _clean(param.help)
            lines.append(f"- {entry}" + (f" — {help_}." if help_ else "."))
    return lines


def _render_command(
    group_path: list[str], cmd: click.Command, out: list[str]
) -> None:
    name = " ".join(["campus", *group_path, cmd.name])
    out.append(f"### `{name}`")
    out.append("")
    help_ = _clean(cmd.help)
    if help_:
        out.append(help_)
    else:
        out.append("> No help text. Add a docstring to the command.")
    out.append("")
    out.append("```")
    out.append(_usage_line(group_path, cmd))
    out.append("```")
    out.append("")
    lines = _render_params(cmd)
    if lines:
        out.append("Arguments/options:")
        out.append("")
        out.extend(lines)
        out.append("")


def _render_group(
    group_path: list[str], group: click.Group, out: list[str]
) -> None:
    name = " ".join(["campus", *group_path])
    out.append(f"## `{name}`")
    out.append("")
    if group.help:
        out.append(_clean(group.help))
        out.append("")
    for sub_name in sorted(group.commands):
        sub = group.commands[sub_name]
        if isinstance(sub, click.Group):
            _render_group([*group_path, sub_name], sub, out)
        else:
            _render_command(group_path, sub, out)


def main() -> None:
    full_group = typer.main.get_group(app)

    out = [HEADER]
    out.append("## Global options")
    out.append("")
    out.append(_clean(full_group.help) or "The campus CLI.")
    out.append("")
    for line in _render_params(full_group):
        out.append(line)
    out.append("")
    out.append("`campus` with no arguments prints the command list.")
    out.append("")

    groups = sorted(full_group.commands.items())
    toc = [
        "",
        "| Group | Commands |",
        "|---|---|",
    ]
    sections: list[str] = []
    for name, group in groups:
        if isinstance(group, click.Group):
            cmd_count = sum(
                len(g.commands) if isinstance(g, click.Group) else 1
                for g in group.commands.values()
            )
            toc.append(
                f"| [`campus {name}`](#{_slug('campus ' + name)}) | "
                f"{_clean(group.help) or '—'} ({cmd_count}) |"
            )
            _render_group([name], group, sections)
        else:
            toc.append(
                f"| [`campus {name}`](#{_slug('campus ' + name)}) | — |"
            )
            _render_command([], group, sections)
    out.extend(toc)
    out.append("")
    out.extend(sections)

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"docs/reference/commands.md -> {len(groups)} groups")


from campus_cli.cli import app  # noqa: E402  (import after module docstring)

if __name__ == "__main__":
    main()
